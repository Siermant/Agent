"""Opt-in outbound paper diagnostics, never remote commands or code updates."""
import base64
import json
import os
import re
from datetime import datetime, timezone
from pathlib import Path
from urllib.error import HTTPError
from urllib.request import Request, build_opener, HTTPRedirectHandler

TARGET = 'Siermant/Agent-diagnostics'
API = 'https://api.github.com/repos/' + TARGET
FILES = {'status': 'status.json', 'hourly': 'portfolios.json', 'daily': 'daily.json'}


class NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


class GitHubSink:
    def __init__(self, token, opener=None):
        if not token or any(c.isspace() for c in token):
            raise ValueError('Missing or invalid diagnostic token')
        self.token = token
        self.opener = opener or build_opener(NoRedirect())

    def request(self, method, suffix, payload=None):
        body = None if payload is None else json.dumps(payload).encode()
        req = Request(API + suffix, data=body, method=method, headers={
            'Authorization': 'Bearer ' + self.token,
            'Accept': 'application/vnd.github+json',
            'X-GitHub-Api-Version': '2022-11-28',
            'Content-Type': 'application/json', 'User-Agent': 'GTA-diagnostics'})
        with self.opener.open(req, timeout=12) as res:
            raw = res.read(2_000_001)
        if len(raw) > 2_000_000:
            raise ValueError('Oversized response')
        return json.loads(raw)

    def send(self, key, payload):
        path = '/contents/' + FILES[key]
        repo = self.request('GET', '')
        if (repo.get('private') is not True or repo.get('visibility') != 'private'
                or repo.get('full_name', '').lower() != TARGET.lower() or repo.get('fork') is not False):
            raise PermissionError('Diagnostic target is not the expected private repository')
        branch = repo.get('default_branch')
        if not isinstance(branch, str) or not re.fullmatch(r'[A-Za-z0-9._-]{1,100}', branch):
            raise ValueError('Invalid diagnostic branch')
        body = {'message': 'Update paper diagnostics', 'branch': branch,
                'content': base64.b64encode(json.dumps(payload, allow_nan=False, ensure_ascii=True).encode()).decode()}
        try:
            current = self.request('GET', path + '?ref=' + branch)
        except HTTPError as exc:
            if exc.code != 404:
                raise
        else:
            sha = current.get('sha', '')
            if current.get('type') != 'file' or not re.fullmatch(r'[a-f0-9]{40}', sha):
                raise ValueError('Invalid diagnostic file')
            body['sha'] = sha
        self.request('PUT', path, body)


class Outbox:
    """Only latest pending snapshot per type; survives restart, bounded to three files."""
    def __init__(self, root):
        self.root = Path(root)
        self.root.mkdir(mode=0o700, parents=True, exist_ok=True)

    def get(self, key):
        path = self.root / FILES[key]
        return json.loads(path.read_text()) if path.exists() else {}

    def put(self, key, value):
        path = self.root / FILES[key]
        temp = path.with_suffix('.tmp')
        fd = os.open(temp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, 'w') as f:
            json.dump(value, f, allow_nan=False)
            f.flush()
            os.fsync(f.fileno())
        os.replace(temp, path)

    def stage(self, key, slot, payload):
        old = self.get(key)
        if old.get('slot') != slot:
            self.put(key, {'slot':slot, 'pending':True, 'payload':payload})

    def flush(self, sink):
        for key in FILES:
            item = self.get(key)
            if item.get('pending'):
                sink.send(key, item['payload'])
                self.put(key, {'slot':item['slot'], 'pending':False})


def snapshots(state, decisions, now):
    """Only fields generated by the paper service; never export arbitrary raw logs."""
    paper = state['paper']
    market = state['market']
    status = {'generated_utc':now.isoformat(), 'version':state['version'], 'real_trading':False,
              'mode':state['mode'], 'market_healthy':bool(market['healthy']),
              'market_checked':market['checked'], 'paper_enabled':bool(paper['enabled']),
              'paper_state':paper['state'] if paper['state'] in ('ok','waiting','disabled','feed_unavailable','incomplete_quotes','day_changed') else 'blocked',
              'backup_state':state.get('backup',{}).get('state','waiting'),
              'backup_day':state.get('backup',{}).get('day')}
    keys = ('account','initial_pln','cash_pln','equity_pln','valued_at','fresh','return_pct','current_drawdown_pct','fees_pln','fills','turnover_pln')
    rows = [{k:r[k] for k in keys} for r in state['statistics']]
    hourly = {'generated_utc':now.isoformat(), 'real_trading':False,'market_healthy':status['market_healthy'],'portfolios':rows}
    daily = {'generated_utc':now.isoformat(),'real_trading':False,'portfolios':rows,
             'history':[{'account':r['account'],'history':[{k:h[k] for k in ('day','at','equity')} for h in r['history']]} for r in state['statistics']],
             'decisions':[{k:r[k] for k in ('account','result','count')} for r in decisions]}
    # Include health changes in the slot to transmit transitions without waiting 15 min.
    health = (status['market_healthy'],status['paper_state'],status['backup_state'])
    return {'status':(str(int(now.timestamp())//900)+':'+str(health),status),
            'hourly':(now.strftime('%Y-%m-%dT%H'),hourly), 'daily':(now.date().isoformat(),daily)}


def run_cycle(outbox, sink, state, decisions, now=None):
    now = now or datetime.now(timezone.utc)
    for key,(slot,payload) in snapshots(state,decisions,now).items():
        outbox.stage(key,slot,payload)
    outbox.flush(sink)
